-- Phase 2: event-only GEX wall migration attribution.
-- Stores only meaningful wall events, never every strike on every poll.

CREATE TABLE IF NOT EXISTS public.gex_strike_attribution (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comparison_id uuid NOT NULL,
    previous_snapshot_id uuid NOT NULL,
    current_snapshot_id uuid NOT NULL,
    expiry_date date NOT NULL,
    option_type text NOT NULL CHECK (option_type IN ('CALL', 'PUT')),
    strike_price numeric NOT NULL CHECK (strike_price > 0),

    wall_event_type text NOT NULL CHECK (
        wall_event_type IN (
            'WINNER_SWITCH',
            'SIGNIFICANT_MAGNITUDE_CHANGE',
            'NEW_EXPOSURE',
            'DISAPPEARED'
        )
    ),
    previous_wall_strike numeric,
    current_wall_strike numeric,
    previous_top3_rank smallint CHECK (previous_top3_rank BETWEEN 1 AND 3),
    current_top3_rank smallint CHECK (current_top3_rank BETWEEN 1 AND 3),

    previous_collected_at timestamptz NOT NULL,
    current_collected_at timestamptz NOT NULL,

    gamma_previous numeric,
    gamma_current numeric,
    oi_previous numeric,
    oi_current numeric,
    spot_previous numeric NOT NULL CHECK (spot_previous > 0),
    spot_current numeric NOT NULL CHECK (spot_current > 0),
    contract_multiplier numeric NOT NULL CHECK (contract_multiplier > 0),

    gex_previous numeric,
    gex_current numeric,
    gex_change numeric,
    gex_change_pct numeric,

    gamma_contribution numeric,
    oi_contribution numeric,
    spot_contribution numeric,

    wall_margin_change numeric,
    margin_gamma_contribution numeric,
    margin_oi_contribution numeric,
    margin_spot_contribution numeric,

    dominant_driver text NOT NULL CHECK (
        dominant_driver IN ('GAMMA', 'OI', 'SPOT', 'MIXED', 'UNATTRIBUTED')
    ),
    attribution_status text NOT NULL CHECK (
        attribution_status IN ('OK', 'NEW_EXPOSURE', 'DISAPPEARED', 'INSUFFICIENT_DATA')
    ),
    threshold_pct numeric NOT NULL DEFAULT 2.0 CHECK (threshold_pct >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT gex_attribution_snapshot_pair_check
        CHECK (previous_snapshot_id <> current_snapshot_id),
    CONSTRAINT gex_attribution_time_order_check
        CHECK (current_collected_at >= previous_collected_at),
    CONSTRAINT gex_attribution_unique_event
        UNIQUE (
            previous_snapshot_id,
            current_snapshot_id,
            expiry_date,
            option_type,
            strike_price
        )
);

CREATE INDEX IF NOT EXISTS idx_gex_attribution_expiry_time
    ON public.gex_strike_attribution (expiry_date, current_collected_at DESC);

CREATE INDEX IF NOT EXISTS idx_gex_attribution_comparison
    ON public.gex_strike_attribution (comparison_id);

CREATE INDEX IF NOT EXISTS idx_gex_attribution_event_type_time
    ON public.gex_strike_attribution (wall_event_type, current_collected_at DESC);

-- The collector uses the Supabase service role. No browser-facing role needs
-- access to this proprietary research table.
ALTER TABLE public.gex_strike_attribution ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.gex_strike_attribution FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.gex_strike_attribution TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.gex_strike_attribution_id_seq TO service_role;
