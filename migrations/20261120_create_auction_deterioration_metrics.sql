-- Phase: Auction Deterioration Shadow Monitor.
-- Compact, one-row-per-completed-AMT-candle research metrics.
-- This migration is intentionally separate from production alerting.

CREATE TABLE IF NOT EXISTS public.auction_deterioration_metrics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exchange text NOT NULL DEFAULT 'BINANCE',
    symbol text NOT NULL DEFAULT 'BTCUSDT',
    timeframe text NOT NULL DEFAULT '30',
    profile_id text NOT NULL,
    candle_open_time timestamptz NOT NULL,
    candle_close_time timestamptz NOT NULL,
    confirmed_state text NOT NULL,

    close_price numeric NOT NULL CHECK (close_price > 0),
    high_price numeric NOT NULL CHECK (high_price > 0),
    low_price numeric NOT NULL CHECK (low_price > 0),
    developing_val numeric NOT NULL,
    developing_poc numeric NOT NULL,
    atr_21 numeric NOT NULL CHECK (atr_21 > 0),

    transition_anchor_time timestamptz NOT NULL,
    transition_anchor_price numeric NOT NULL CHECK (transition_anchor_price > 0),

    downside_close_excursion_usd numeric NOT NULL DEFAULT 0 CHECK (downside_close_excursion_usd >= 0),
    upside_close_excursion_usd numeric NOT NULL DEFAULT 0 CHECK (upside_close_excursion_usd >= 0),
    downside_wick_excursion_usd numeric NOT NULL DEFAULT 0 CHECK (downside_wick_excursion_usd >= 0),
    upside_wick_excursion_usd numeric NOT NULL DEFAULT 0 CHECK (upside_wick_excursion_usd >= 0),

    downside_close_excursion_atr numeric NOT NULL DEFAULT 0 CHECK (downside_close_excursion_atr >= 0),
    upside_close_excursion_atr numeric NOT NULL DEFAULT 0 CHECK (upside_close_excursion_atr >= 0),
    downside_wick_excursion_atr numeric NOT NULL DEFAULT 0 CHECK (downside_wick_excursion_atr >= 0),
    upside_wick_excursion_atr numeric NOT NULL DEFAULT 0 CHECK (upside_wick_excursion_atr >= 0),

    downside_close_excursion_pct numeric NOT NULL DEFAULT 0 CHECK (downside_close_excursion_pct >= 0),
    upside_close_excursion_pct numeric NOT NULL DEFAULT 0 CHECK (upside_close_excursion_pct >= 0),
    downside_wick_excursion_pct numeric NOT NULL DEFAULT 0 CHECK (downside_wick_excursion_pct >= 0),
    upside_wick_excursion_pct numeric NOT NULL DEFAULT 0 CHECK (upside_wick_excursion_pct >= 0),
    poc_distance_atr numeric NOT NULL CHECK (poc_distance_atr >= 0),

    val_test_active boolean NOT NULL DEFAULT false,
    val_test_started_at timestamptz,
    val_test_level numeric,
    val_test_status text NOT NULL DEFAULT 'NONE' CHECK (
        val_test_status IN (
            'NONE', 'STARTED', 'CONTINUING', 'REJECTED',
            'BROKEN', 'INCOMPLETE_GAP', 'RESET_STATE_CHANGE'
        )
    ),
    val_test_count integer NOT NULL DEFAULT 0 CHECK (val_test_count >= 0),
    val_rejection_count integer NOT NULL DEFAULT 0 CHECK (val_rejection_count >= 0),

    calculation_version text NOT NULL DEFAULT 'shadow-v1.0',
    created_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT auction_deterioration_unique_candle
        UNIQUE (exchange, symbol, timeframe, profile_id, candle_close_time),
    CONSTRAINT auction_deterioration_ohlc_check
        CHECK (low_price <= close_price AND close_price <= high_price),
    CONSTRAINT auction_deterioration_counts_check
        CHECK (val_rejection_count <= val_test_count),
    CONSTRAINT auction_deterioration_active_episode_check
        CHECK (
            (val_test_active AND val_test_started_at IS NOT NULL AND val_test_level IS NOT NULL)
            OR
            (NOT val_test_active)
        )
);

CREATE INDEX IF NOT EXISTS idx_auction_deterioration_close_time
    ON public.auction_deterioration_metrics (candle_close_time DESC);

CREATE INDEX IF NOT EXISTS idx_auction_deterioration_profile_time
    ON public.auction_deterioration_metrics (profile_id, candle_close_time DESC);

CREATE INDEX IF NOT EXISTS idx_auction_deterioration_state_time
    ON public.auction_deterioration_metrics (confirmed_state, candle_close_time DESC);

ALTER TABLE public.auction_deterioration_metrics ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.auction_deterioration_metrics FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.auction_deterioration_metrics TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.auction_deterioration_metrics_id_seq TO service_role;
